/**
 * Create a translator function for the given locale.
 * Falls back to English if a key is missing in the selected dictionary.
 * Supports `{param}` interpolation: t('key', { name: 'Foo' })
 */
export function createTranslator(locale: Language) {
  const dict = dictionaries[locale] ?? dictionaries.en
  const fallback = dictionaries.en

  return (key: string, params?: Record<string, string | number>): string => {
    let val = dict[key] ?? fallback[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        val = val.replace(`{${k}}`, String(v))
      }
    }
    return val
  }
}

export type Translator = ReturnType<typeof createTranslator>
